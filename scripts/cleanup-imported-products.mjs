import { readFileSync, writeFileSync } from "node:fs";

const outputPath = "packages/domain/src/imported-products.ts";
const source = readFileSync(outputPath, "utf8");
const executable = source
  .replace(/^import type[^\n]+\n\n/, "")
  .replace(/export const (imported\w+): [^=]+ =/g, "const $1 =");

const data = new Function(
  `${executable}\nreturn { importedBrands, importedProducts, importedVariants, importedInventoryItems };`,
)();

const seenProductKeys = new Set();
const removedProductIds = new Set();
const products = data.importedProducts.filter((product) => {
  const key = `${product.nameFa ?? ""}|${product.nameEn ?? ""}`.toLowerCase();
  if (seenProductKeys.has(key)) {
    removedProductIds.add(product.id);
    return false;
  }
  seenProductKeys.add(key);
  return true;
});

const removedVariantIds = new Set(
  data.importedVariants
    .filter((variant) => removedProductIds.has(variant.productId))
    .map((variant) => variant.id),
);

const variants = data.importedVariants.filter((variant) => !removedVariantIds.has(variant.id));
const inventoryItems = data.importedInventoryItems.filter(
  (item) => !removedVariantIds.has(item.variantId),
);
const brands = data.importedBrands.filter(Boolean);

const content = `import type { Brand, InventoryItem, Product, ProductVariant } from "@ufo/types";

// Generated by scripts/import-client-catalog.mjs from the client supplied catalog on 2026-08-05.
// Extra device, coil, cartridge and accessory products appended from the 2026-08-09 user list.
export const importedBrands: Brand[] = ${JSON.stringify(brands, null, 2)};

export const importedProducts: Product[] = ${JSON.stringify(products, null, 2)};

export const importedVariants: ProductVariant[] = ${JSON.stringify(variants, null, 2)};

export const importedInventoryItems: InventoryItem[] = ${JSON.stringify(inventoryItems, null, 2)};
`;

writeFileSync(outputPath, content, "utf8");
console.log(
  `Removed ${removedProductIds.size} duplicate products and ${removedVariantIds.size} variants.`,
);
